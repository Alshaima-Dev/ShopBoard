export type MessageKey = keyof typeof messages.en
export type TranslationValues = Record<string, string | number>

export const isLanguage = (language: unknown): language is Language =>
  typeof language === 'string' && Object.hasOwn(languages, language)
export const getLanguage = (language: unknown): Language =>
  isLanguage(language) ? language : 'en'
export function translate(
  language: unknown,
  key: string,
  values: TranslationValues = {},
): string {
  const dictionary = messages[getLanguage(language)]
  const message = Object.hasOwn(dictionary, key)
    ? dictionary[key as MessageKey]
    : undefined
  if (message === undefined)
    throw new Error(`Missing translation: ${language}.${key}`)
  return message.replace(/\{(\w+)\}/g, (_, name) =>
    String(values[name] ?? `{${name}}`),
  )
}
export function getProductText(
  product: Product,
  language: string = 'en',
): ProductTranslation {
  return product.translations[getLanguage(language)]
}
export function formatNumber(number: number, language: string = 'en'): string {
  return new Intl.NumberFormat(languages[getLanguage(language)].locale).format(
    number,
  )
}

export function formatPrice(price: number, language = 'en') {
  return new Intl.NumberFormat(languages[getLanguage(language)].locale, {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(price)
}
